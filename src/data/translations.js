export function getTranslation(langKeyOrName, key) {
  let langName = langKeyOrName;
  
  if (typeof langKeyOrName === 'object' && langKeyOrName?.name) {
    langName = langKeyOrName.name;
  } else {
    const matchedLang = SUPPORTED_LANGUAGES.find(
      l => l.name === langKeyOrName || l.code === langKeyOrName
    );
    if (matchedLang) {
      langName = matchedLang.name;
    }
  }

  const langDict = translations[langName] || translations["English"];
  return langDict[key] || translations["English"][key] || key;
}